"""Narrow structural interfaces for use cases and test doubles."""
from typing import Protocol, TypeVar
from pydantic import BaseModel
T = TypeVar("T", bound=BaseModel)

class StructuredModel(Protocol):
    async def structured(self, messages: list[dict], schema: type[T], retries: int = 2, temperature: float = 0) -> T: ...

class Embedder(Protocol):
    embed_model: str
    async def embed(self, texts: list[str]) -> list[list[float]]: ...

class Retriever(Protocol):
    async def inspect(self, query, options): ...
    async def search(self, query, k, options=None): ...

class ChunkSink(Protocol):
    async def upsert(self, chunks) -> None: ...

class ClaimRepository(Protocol):
    def get(self, claim_number: str) -> dict: ...
    def list_numbers(self) -> list[str]: ...
